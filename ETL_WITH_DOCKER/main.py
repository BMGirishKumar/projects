from fastapi import FastAPI, HTTPException
import pandas as pd
import os

app = FastAPI(title="No-DB ETL Analytics API")
SUMMARY_FILE = "data/summary_metrics.csv"

@app.get("/")
def read_root():
    """Welcome screen endpoint."""
    return {
        "status": "Online",
        "message": "Welcome to the FastAPI Analytics Engine",
        "instructions": "Navigate to /metrics to see processed data, or /trigger-etl to re-run the pipeline."
    }

@app.get("/metrics")
def get_metrics():
    """Reads and returns the processed data calculated by the ETL script."""
    if not os.path.exists(SUMMARY_FILE):
        raise HTTPException(
            status_code=404, 
            detail="Analytics metrics are not ready yet. Please wait a moment or trigger the ETL pipeline."
        )
        
    # Read the summary file generated by the ETL container
    df = pd.read_csv(SUMMARY_FILE)
    
    # Convert data frame to JSON list of objects format
    return df.to_dict(orient="records")

@app.get("/trigger-etl")
def trigger_etl():
    """Allows a user to manually tell the system to re-process the CSV file."""
    etl_script = "etl/run_pipeline.py"
    
    if os.path.exists(etl_script):
        # Dynamically execute the script file from within the app container
        os.system(f"python {etl_script}")
        return {"status": "Success", "message": "ETL pipeline executed and data refreshed successfully!"}
    
    raise HTTPException(status_code=500, detail="ETL script file not found inside the container system.")
